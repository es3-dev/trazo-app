CREATE TABLE "TBL_EVIDENCIAS_FOTOGRAFICAS" (
  "id" SERIAL PRIMARY KEY,
  "id_parte" INTEGER NOT NULL REFERENCES "TBL_PARTE_DIARIO"("id_parte") ON DELETE CASCADE,
  "nombre_original" VARCHAR(255) NOT NULL,
  "ruta" VARCHAR(255) NOT NULL UNIQUE,
  "descripcion" VARCHAR(500),
  "mime_type" VARCHAR(100) NOT NULL,
  "tamano" INTEGER NOT NULL,
  "created_at" TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "evidencias_parte_idx" ON "TBL_EVIDENCIAS_FOTOGRAFICAS"("id_parte");
